# WHILE LOOP

# Definition:
# A while loop executes a block of code repeatedly
# as long as the condition remains True.

# Syntax:

# while condition:
#     code


# Example:

count = 1

while count <= 5:
    print(count)
    count += 1


# Output:
# 1
# 2
# 3
# 4
# 5


# Important:
# If the condition never becomes False,
# the loop runs forever (infinite loop).


# Infinite loop example:

# while True:
#     print("Running forever")


# Common Uses of while loop:
# 1. User input validation
# 2. Menu-driven programs
# 3. Repeating tasks until condition changes
# 4. Game loops
# 5. Login systems


