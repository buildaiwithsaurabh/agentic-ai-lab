# ==========================================
# CRUD OPERATIONS IN FASTAPI
# ==========================================

# CRUD stands for:
#
# C = Create
# R = Read
# U = Update
# D = Delete
#
# CRUD operations are used in almost every application.


# ==========================================
# CREATE
# ==========================================

# Used to create new data.
#
# HTTP Method:
# POST
#
# Example:
#
# POST /products


# ==========================================
# READ
# ==========================================

# Used to retrieve data.
#
# HTTP Method:
# GET
#
# Examples:
#
# GET /products
# GET /products/1


# ==========================================
# UPDATE
# ==========================================

# Used to update existing data.
#
# HTTP Method:
# PUT
#
# Example:
#
# PUT /products/1


# ==========================================
# DELETE
# ==========================================

# Used to remove data.
#
# HTTP Method:
# DELETE
#
# Example:
#
# DELETE /products/1


# ==========================================
# CRUD TABLE
# ==========================================

# Create  -> POST
# Read    -> GET
# Update  -> PUT
# Delete  -> DELETE


